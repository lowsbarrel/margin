pub fn bind_editor_keys(cx: &mut App) {
    let context = Some(EDITOR_CONTEXT);
    let bindings = [
        binding("left", MoveLeft, context, cx),
        binding("right", MoveRight, context, cx),
        binding("up", MoveUp, context, cx),
        binding("down", MoveDown, context, cx),
        binding("alt-left", MoveWordLeft, context, cx),
        binding("alt-right", MoveWordRight, context, cx),
        binding("ctrl-left", MoveWordLeft, context, cx),
        binding("ctrl-right", MoveWordRight, context, cx),
        binding("home", MoveLineStart, context, cx),
        binding("end", MoveLineEnd, context, cx),
        binding("cmd-left", MoveLineStart, context, cx),
        binding("cmd-right", MoveLineEnd, context, cx),
        binding("cmd-up", MoveDocStart, context, cx),
        binding("cmd-down", MoveDocEnd, context, cx),
        binding("ctrl-home", MoveDocStart, context, cx),
        binding("ctrl-end", MoveDocEnd, context, cx),
        binding("pageup", MovePageUp, context, cx),
        binding("pagedown", MovePageDown, context, cx),
        binding("shift-left", SelectLeft, context, cx),
        binding("shift-right", SelectRight, context, cx),
        binding("shift-up", SelectUp, context, cx),
        binding("shift-down", SelectDown, context, cx),
        binding("alt-shift-left", SelectWordLeft, context, cx),
        binding("alt-shift-right", SelectWordRight, context, cx),
        binding("ctrl-shift-left", SelectWordLeft, context, cx),
        binding("ctrl-shift-right", SelectWordRight, context, cx),
        binding("shift-home", SelectLineStart, context, cx),
        binding("shift-end", SelectLineEnd, context, cx),
        binding("cmd-shift-left", SelectLineStart, context, cx),
        binding("cmd-shift-right", SelectLineEnd, context, cx),
        binding("cmd-shift-up", SelectDocStart, context, cx),
        binding("cmd-shift-down", SelectDocEnd, context, cx),
        binding("ctrl-shift-home", SelectDocStart, context, cx),
        binding("ctrl-shift-end", SelectDocEnd, context, cx),
        binding("shift-pageup", SelectPageUp, context, cx),
        binding("shift-pagedown", SelectPageDown, context, cx),
        binding("secondary-a", SelectAll, context, cx),
        binding("backspace", Backspace, context, cx),
        binding("shift-backspace", Backspace, context, cx),
        binding("delete", Delete, context, cx),
        binding("alt-backspace", DeleteWordLeft, context, cx),
        binding("ctrl-backspace", DeleteWordLeft, context, cx),
        binding("alt-delete", DeleteWordRight, context, cx),
        binding("ctrl-delete", DeleteWordRight, context, cx),
        binding("cmd-backspace", DeleteToLineStart, context, cx),
        binding("cmd-delete", DeleteToLineEnd, context, cx),
        binding("enter", Newline, context, cx),
        binding("shift-enter", SoftBreak, context, cx),
        binding("tab", Indent, context, cx),
        binding("shift-tab", Outdent, context, cx),
        binding("secondary-]", Indent, context, cx),
        binding("secondary-[", Outdent, context, cx),
        binding("secondary-z", Undo, context, cx),
        binding("secondary-shift-z", Redo, context, cx),
        binding("secondary-y", Redo, context, cx),
        binding("secondary-x", Cut, context, cx),
        binding("secondary-c", Copy, context, cx),
        binding("secondary-v", Paste, context, cx),
        binding("secondary-b", ToggleBold, context, cx),
        binding("secondary-i", ToggleItalic, context, cx),
        binding("secondary-e", ToggleCode, context, cx),
        binding("secondary-shift-x", ToggleStrike, context, cx),
        binding("secondary-shift-h", ToggleHighlight, context, cx),
        binding("secondary-/", ToggleComment, context, cx),
        binding("secondary-k", InsertLink, context, cx),
        binding("secondary-shift-7", ToggleOrderedList, context, cx),
        binding("secondary-shift-8", ToggleBulletList, context, cx),
        binding("secondary-shift-9", ToggleTaskList, context, cx),
        binding("secondary-1", ToggleHeading1, context, cx),
        binding("secondary-2", ToggleHeading2, context, cx),
        binding("secondary-3", ToggleHeading3, context, cx),
        binding("secondary-4", ToggleHeading4, context, cx),
        binding("secondary-5", ToggleHeading5, context, cx),
        binding("secondary-6", ToggleHeading6, context, cx),
        binding("secondary-l", CycleChecklist, context, cx),
        binding("secondary-d", DeleteLine, context, cx),
        binding("alt-up", MoveLineUp, context, cx),
        binding("alt-down", MoveLineDown, context, cx),
        binding("alt-shift-up", SelectParagraphUp, context, cx),
        binding("alt-shift-down", SelectParagraphDown, context, cx),
        binding("secondary-shift-k", DeleteLine, context, cx),
        binding("secondary-g", FindNextMatch, context, cx),
        binding("f3", FindNextMatch, context, cx),
        binding("secondary-shift-g", FindPreviousMatch, context, cx),
        binding("shift-f3", FindPreviousMatch, context, cx),
        binding("secondary-shift-l", SelectMatches, context, cx),
        binding("escape", Cancel, context, cx),
        binding("shift-f10", OpenContextMenu, context, cx),
    ];
    cx.bind_keys(bindings);
    if cfg!(target_os = "macos") {
        bind_emacs_keys(context, cx);
    }
}

fn bind_emacs_keys(context: Option<&str>, cx: &mut App) {
    let emacs = [
        binding("ctrl-a", MoveLineStart, context, cx),
        binding("ctrl-e", MoveLineEnd, context, cx),
        binding("ctrl-b", MoveLeft, context, cx),
        binding("ctrl-f", MoveRight, context, cx),
        binding("ctrl-p", MoveUp, context, cx),
        binding("ctrl-n", MoveDown, context, cx),
        binding("ctrl-d", Delete, context, cx),
        binding("ctrl-h", Backspace, context, cx),
        binding("ctrl-k", DeleteToLineEnd, context, cx),
        binding("ctrl-alt-h", DeleteWordLeft, context, cx),
    ];
    cx.bind_keys(emacs);
}
